
import os

# Import the Ollama Python library to communicate with the local model.
import ollama

# Model used for classification. Override with OLLAMA_MODEL (it must be pulled in Ollama).
MODEL_NAME = os.environ.get("OLLAMA_MODEL") or "llama3.2:3b"


def generate_response(prompt: str, json_mode: bool = False) -> str:
    """
    Send a prompt to Ollama and return the model's response as text.

    Args:
        prompt: The instruction or question sent to the LLM.
        json_mode: Make Ollama answer with a single JSON object and no surrounding chatter.

    Returns:
        The text generated by the model.
    """

    # Send the prompt to the locally running Ollama server.
    response = ollama.chat(
        model=MODEL_NAME,
        messages=[
            {
                "role": "user",
                "content": prompt,
            }
        ],
        format="json" if json_mode else None,
    )

    # Extract the generated text from the response.
    answer = response["message"]["content"]

    # Return the answer to whichever part of our application called this function.
    return answer


# Run a small test when this file is executed directly.
if __name__ == "__main__":

    # Define a sample prompt to test the model.
    test_prompt = (
        "Explain what a bank account balance is in simple words. "
        "Answer in two sentences."
    )

    # Generate a response using our local LLM.
    result = generate_response(test_prompt)

    # Print the model's answer.
    print("\nLLM Response:")
    print(result)
