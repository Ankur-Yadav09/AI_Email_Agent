
import os

# Import the Ollama Python library to communicate with the local model.
import ollama

from utils import tracing

# Model used for classification. Override with OLLAMA_MODEL (it must be pulled in Ollama).
MODEL_NAME = os.environ.get("OLLAMA_MODEL") or "llama3.2:3b"

# A hung model must not hang a request: on timeout the email falls back to "Needs a person".
TIMEOUT_SECONDS = float(os.environ.get("OLLAMA_TIMEOUT_SECONDS") or 120)

# Same email, same answer: no sampling randomness, and an explicit context window instead of the default.
OPTIONS = {"temperature": 0, "seed": 7, "num_ctx": int(os.environ.get("OLLAMA_NUM_CTX") or 4096)}

# Keep the model in memory between emails; loading it cold adds many seconds to the first email.
KEEP_ALIVE = os.environ.get("OLLAMA_KEEP_ALIVE") or "30m"


def generate_response(prompt: str, json_mode: bool = False) -> str:
    """
    Send a prompt to Ollama and return the model's response as text.

    Args:
        prompt: The instruction or question sent to the LLM.
        json_mode: Make Ollama answer with a single JSON object and no surrounding chatter.

    Returns:
        The text generated by the model.
    """

    # Send the prompt to the locally running Ollama server (as one trace span: model, tokens, timings).
    with tracing.span(
        "llm.chat", "LLM",
        llm__model_name=MODEL_NAME, llm__json_mode=json_mode, llm__invocation_parameters=OPTIONS,
        input__size_chars=len(prompt),
    ) as current:
        if tracing.content_enabled():  # customer content: only when explicitly switched on, and masked
            tracing.set_attributes(current, {"input.value": prompt})

        response = ollama.Client(timeout=TIMEOUT_SECONDS).chat(
            model=MODEL_NAME,
            messages=[
                {
                    "role": "user",
                    "content": prompt,
                }
            ],
            format="json" if json_mode else None,
            options=OPTIONS,
            keep_alive=KEEP_ALIVE,
        )

        # Extract the generated text from the response.
        answer = response["message"]["content"]

        # Ollama reports token counts and where the time went (nanoseconds); a missing field is simply skipped.
        def ms(name):
            value = getattr(response, name, None)
            return round(value / 1e6) if isinstance(value, (int, float)) else None

        prompt_tokens, answer_tokens = getattr(response, "prompt_eval_count", None), getattr(response, "eval_count", None)
        tracing.set_attributes(current, {
            "llm.token_count.prompt": prompt_tokens,
            "llm.token_count.completion": answer_tokens,
            "llm.token_count.total": prompt_tokens + answer_tokens if prompt_tokens is not None and answer_tokens is not None else None,
            "llm.load_ms": ms("load_duration"),            # model loading: large only on a cold start
            "llm.prompt_eval_ms": ms("prompt_eval_duration"),
            "llm.generate_ms": ms("eval_duration"),
            "llm.total_ms": ms("total_duration"),
            "output.size_chars": len(answer),
        })
        if tracing.content_enabled():
            tracing.set_attributes(current, {"output.value": answer})

    # Return the answer to whichever part of our application called this function.
    return answer


# Run a small test when this file is executed directly.
if __name__ == "__main__":

    # Define a sample prompt to test the model.
    test_prompt = (
        "Explain what a bank account balance is in simple words. "
        "Answer in two sentences."
    )

    # Generate a response using our local LLM.
    result = generate_response(test_prompt)

    # Print the model's answer.
    print("\nLLM Response:")
    print(result)
